/** 城墙基体（一段）：主体墙 + 垛口 + 城门洞 */
function wallBody(x, z, w, d, h, wallC, trimC) {
	const p = [
		box([x, h / 2, z], [w, h, d], wallC),
		...row(3, (i) => box([x - w / 2 + (w / 3) * i + w / 6, h + 0.035, z], [w / 5, 0.07, d * 0.6], trimC)),
		box([x, h / 2, z + d / 2 + 0.005], [w * 0.28, h * 0.5, 0.01], C.black),
	];
	return p;
}

function sanguoHouse(d, lv) {
	const p = [];
	let y = 0;
	if (lv === 0) {
		// 夯土寨
		p.push(box([0, y + 0.14, 0], [0.62, 0.28, 0.58], C.earth, { name: "color-wall" }));
		p.push(...row(5, (i) => box([-0.26 + i * 0.13, y + 0.3, 0], [0.04, 0.06, 0.04], C.darkWood)));
		p.push(box([0, y + 0.35, 0], [0.3, 0.04, 0.04], C.darkWood));
		y += 0.32;
	} else {
		// 砖石城
		const h = 0.24 + lv * 0.04;
		p.push(box([0, y + h / 2, 0], [0.66, h, 0.6], d.wall, { name: "color-wall" }));
		p.push(...row(5, (i) => box([-0.26 + i * 0.13, y + h + 0.03, 0], [0.08, 0.06, 0.5], d.trim)));
		y += h + 0.06;
		if (lv >= 2) {
			// 谯楼
			const th = 0.22;
			p.push(box([0, y + th / 2, 0], [0.34, th, 0.34], C.wood));
			p.push(box([0, y + th / 2, 0.175], [0.1, 0.12, 0.01], C.black));
			p.push(box([0, y + th + 0.03, 0], [0.42, 0.05, 0.42], d.roof));
			p.push(box([0, y + th + 0.08, 0], [0.24, 0.05, 0.24], d.trim));
			y += th + 0.1;
		}
		if (lv >= 3) {
			// 瓮城
			p.push(box([0, 0.2, 0.38], [0.4, 0.4, 0.16], C.gray));
			p.push(...row(3, (i) => box([-0.14 + i * 0.14, 0.43, 0.38], [0.06, 0.06, 0.12], C.darkGray)));
			p.push(box([0, 0.2, 0.465], [0.1, 0.2, 0.01], C.black));
			// 箭楼
			p.push(box([-0.3, y + 0.12, -0.06], [0.16, 0.24, 0.16], C.wood));
			p.push(box([-0.3, y + 0.26, -0.06], [0.2, 0.04, 0.2], d.roof));
			p.push(box([0.3, y + 0.12, -0.06], [0.16, 0.24, 0.16], C.wood));
			p.push(box([0.3, y + 0.26, -0.06], [0.2, 0.04, 0.2], d.roof));
		}
		if (lv >= 4) {
			// 双阙
			p.push(box([-0.38, y + 0.16, 0], [0.14, 0.32, 0.14], d.wall));
			p.push(box([-0.38, y + 0.34, 0], [0.18, 0.04, 0.18], d.roof));
			p.push(box([0.38, y + 0.16, 0], [0.14, 0.32, 0.14], d.wall));
			p.push(box([0.38, y + 0.34, 0], [0.18, 0.04, 0.18], d.roof));
		}
	}
	p.push(...d.deco(y));
	return p;
}

export function buildDistrictHouses() {
	const out = [];
	for (const d of DISTRICTS) {
		for (let lv = 0; lv < 5; lv++) {
			out.push(model(`house-${d.key}-${lv}`, `${d.name}·${lv}级`, sanguoHouse(d, lv)));
		}
	}
	return out;
}

